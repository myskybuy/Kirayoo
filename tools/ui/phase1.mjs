import { chromium } from 'playwright-core';
const S = process.argv[2];
const b = await chromium.launch({ channel: 'msedge' });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
const log = (...a) => console.log(...a);
await p.goto('http://localhost:3001/'); log('1 first visit ->', p.url());
await p.getByRole('radio', { name: /Pune/ }).click();
await p.getByPlaceholder('Search areas').fill('ban');
await p.getByRole('radio', { name: 'Baner' }).click();
await p.screenshot({ path: S + '/shots/loc.png' });
await p.getByRole('button', { name: /Show items in Baner/ }).click();
await p.waitForLoadState('networkidle'); log('2 after location ->', p.url());
await p.goto('http://localhost:3001/profile'); log('3 profile logged out ->', p.url());
await p.getByLabel('Email address').fill('newbie@kirayo.test');
await p.getByRole('button', { name: /Send code/ }).click();
await p.waitForURL('**/verify'); log('4 verify page');
const code = (await p.locator('.k-alert.info b').textContent()).trim(); log('  dev code', code);
// wrong code first
await p.getByLabel('Digit 1').fill('000000');
await p.getByLabel('New here? Your full name').fill('Newbie Tester');
await p.getByRole('button', { name: /Verify/ }).click();
await p.locator('.k-alert.err').waitFor(); log('5 wrong code ->', await p.locator('.k-alert.err').textContent());
await p.getByLabel('Digit 1').fill(code);
await p.getByRole('button', { name: /Verify/ }).click();
await p.waitForURL('**/profile'); log('6 after verify ->', p.url());
await p.screenshot({ path: S + '/shots/profile.png', fullPage: true });
log('  header has chat icon:', await p.locator('a[aria-label^="Messages"]').count());
await p.getByLabel('Phone').fill('98450 12345');
await p.getByRole('button', { name: 'Save changes' }).click();
await p.locator('.k-alert.ok').waitFor(); log('7 save ->', await p.locator('.k-alert.ok').textContent());
await p.goto('http://localhost:3001/owner'); log('8 /owner unverified ->', p.url());
await p.goto('http://localhost:3001/admin'); log('9 /admin non-admin ->', p.url());
await p.goto('http://localhost:3001/profile');
await p.getByRole('button', { name: 'Log out' }).first().click();
await p.waitForURL('http://localhost:3001/'); log('10 logout ->', p.url(), 'login btn:', await p.getByRole('link', { name: 'Log in' }).count());
log('errors:', errs);
await b.close();
